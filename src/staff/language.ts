export function translateCopy(source: string, language: string) {
  if (language !== 'es') return source;
  const clean = source.trim().replace(/\s+/g, ' ');
  const translated =
    spanish[clean] ??
    clean
      .replace(/\bMIN PLAN\b/g, 'MIN PREVISTOS')
      .replace(/\bmin break\b/g, 'min de descanso')
      .replace(/\(\+1 day\)/g, '(+1 día)')
      .replace(/^(\d{4}-\d{2}-\d{2}) through /, '$1 hasta ');
  return source.replace(source.trim(), translated);
}
export function setupLanguage() {
  const storageKey = 'gmz-staff-language';
  let language = 'es';
  try {
    const saved = localStorage.getItem(storageKey);
    if (saved === 'es' || saved === 'en') language = saved;
  } catch {}
  // Keep originals separate from displayed copy, so switching never changes form data.
  const originals = new WeakMap<Node, { source: string; display: string }>();
  const attributes = new WeakMap<Element, Map<string, { source: string; display: string }>>();
  const skipped = 'script,style,textarea,[data-no-translate],#today-label';
  const observer = new MutationObserver(() => apply());
  function apply() {
    observer.disconnect();
    document.documentElement.lang = language;
    document.title = translateCopy('GMZ Staff · Prototype', language);
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node: Node | null;
    while ((node = walker.nextNode())) {
      if (node.parentElement?.closest(skipped)) continue;
      const current = node.nodeValue || '';
      if (!current.trim()) continue;
      const old = originals.get(node),
        source = old && current === old.display ? old.source : current,
        display = translateCopy(source, language);
      originals.set(node, { source, display });
      if (display !== current) node.nodeValue = display;
    }
    document.querySelectorAll('[placeholder],[aria-label]').forEach((el) => {
      if (el.closest('[data-no-translate]')) return;
      const values = attributes.get(el) || new Map();
      for (const attr of ['placeholder', 'aria-label']) {
        const current = el.getAttribute(attr);
        if (current === null) continue;
        const old = values.get(attr),
          source = old && current === old.display ? old.source : current,
          display = translateCopy(source, language);
        values.set(attr, { source, display });
        if (current !== display) el.setAttribute(attr, display);
      }
      attributes.set(el, values);
    });
    const date = document.getElementById('today-label');
    if (date)
      date.textContent = new Intl.DateTimeFormat(language === 'es' ? 'es-MX' : 'en-US', {
        timeZone: 'America/Los_Angeles',
        weekday: 'long',
        month: 'long',
        day: 'numeric',
      })
        .format(Date.now())
        .toLocaleUpperCase(language);
    document
      .querySelectorAll<HTMLButtonElement>('[data-language]')
      .forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.language === language)));
    observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  }
  document.querySelectorAll<HTMLButtonElement>('[data-language]').forEach((button) =>
    button.addEventListener('click', () => {
      language = button.dataset.language === 'es' ? 'es' : 'en';
      try {
        localStorage.setItem(storageKey, language);
      } catch {}
      apply();
    }),
  );
  apply();
}
